// docs/TODO.md T-206, docs/timezone-requirements.md TZ-9 (requirements
// b.6): the planning layer against EVERY zone with a transition in
// 2026/2027, with the oracle a checked-in table generated by
// scripts/gen_dst_fixture.dart from `package:timezone`'s own bundled
// database (its version is recorded in the table).
//
// Why that database and not the system tzdata (decided in T-206's
// implementation step): the sweep plans with `package:timezone`'s rules -
// the only way to inject a zone other than the process's own - so its
// expected values must come from the SAME rules source. With a table from
// another database, every zone the two disagree on reads as a planning
// defect: package:timezone 0.11.1 bundles tzdata 2025c, the dev VM had
// 2026c, and nine zones differ (Africa/Casablanca, Africa/El_Aaiun,
// America/Edmonton, America/Vancouver, America/Yellowknife, Canada/Mountain,
// Canada/Pacific, Europe/Chisinau, Europe/Tiraspol). The data cross-check
// below therefore only guards the table against a package upgrade without
// regeneration.
//
// The system tzdata is still compared, informationally: a second table,
// test/fixtures/dst_transitions_2026_2027_system_tzdata.json, from
// scripts/gen_dst_fixture.py (Python `zoneinfo`). Zones whose rules differ
// are REPORTED as a skip reason, not failed - the known limitation recorded
// in docs/TODO.md T-206: a device uses the OPERATING SYSTEM's tzdata, which
// may be newer than the package's, so for those zones this sweep does not
// describe the device's rules. For every zone whose rules agree, the two
// tables' R_plan columns must be identical (red): two brute-force generators
// in two languages, so an algorithm error in either shows.
//
// Independent of the app's ALGORITHM either way: both tables' R_plan values
// come from a brute-force minute scan of TZ-1's definition, not from the
// app's probing and bisection.
//
// Pure layer only, and the result does not depend on the process zone, so
// it runs in CI's UTC leg only - ten identical runs buy nothing. Stated
// limits (G#16): it asserts exact values (T) only for holds, drift gets the
// step bound (G) only; persistence, checkpoint 2 and `deviceOffsetAt` are
// the process-zone tests' job (test/replan_dst_test.dart), in all ten legs.
//
// Regenerate with (from the repository root):
//   dart run scripts/gen_dst_fixture.dart > test/fixtures/dst_transitions_2026_2027.json
//   python3 scripts/gen_dst_fixture.py > test/fixtures/dst_transitions_2026_2027_system_tzdata.json

